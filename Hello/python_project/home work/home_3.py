type_material = input("Введите тип учебного материала (книга/видео): ")
cost = int(input("Введите стоимость учебного материала: "))
category_material = input("Введите категорию учебного материала: ")

if cost > 0:
    print(f'Материал добавлен: Тип - {type_material}, Стоимость - {cost}, Категория – {category_material}')
else:
    print("Ошибка: Стоимость учебного материала должна быть больше нуля.")

